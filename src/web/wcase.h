// capital -> small, 0 when c has none
static uint32_t wcase_lower(uint32_t c) {
    if (c < 0x41) return c;
    for (unsigned i = 0; i < sizeof WCM / sizeof WCM[0]; i++) {
        const struct wcm* m = &WCM[i];
        if (c < m->lo || c > m->hi) continue;
        if (m->kind == 0) return (uint32_t)((int32_t)c + m->d);
        if (((c - m->lo) & 1) == 0) return c + 1;
    }
    return c;
}

static uint32_t wcase_upper(uint32_t c) {
    // lowercase letters that map to a capital which is not their table inverse
    switch (c) {
    case 0xB5: return 0x39C;
    case 0xFF: return 0x178;
    case 0x131: return 0x49;
    case 0x17F: return 0x53;
    case 0x1C5: return 0x1C4; case 0x1C8: return 0x1C7; case 0x1CB: return 0x1CA; case 0x1F2: return 0x1F1;
    case 0x345: case 0x1FBE: return 0x399;
    case 0x3C2: return 0x3A3;
    case 0x3D0: return 0x392; case 0x3D1: return 0x398; case 0x3D5: return 0x3A6; case 0x3D6: return 0x3A0;
    case 0x3F0: return 0x39A; case 0x3F1: return 0x3A1; case 0x3F5: return 0x395;
    case 0x1E9B: return 0x1E60;
    case 0x1C80: return 0x412; case 0x1C81: return 0x414; case 0x1C82: return 0x41E; case 0x1C83: return 0x421;
    case 0x1C84: case 0x1C85: return 0x422; case 0x1C86: return 0x42A; case 0x1C87: return 0x462; case 0x1C88: return 0xA64A;
    case 0x3B8: return 0x398;
    }
    if (c >= 0x10D0 && c <= 0x10FA) return c + 3008;            // Georgian: Mkhedruli to Mtavruli
    if (c >= 0x10FD && c <= 0x10FF) return c + 3008;
    if (c >= 0xAB70 && c <= 0xABBF) return c - 38864;           // Cherokee small letters
    if (c >= 0x13F8 && c <= 0x13FD) return c - 8;
    if (c < 0x61) return c;
    for (unsigned i = 0; i < sizeof WCM / sizeof WCM[0]; i++) {
        const struct wcm* m = &WCM[i];
        if (m->kind == 0) {
            int32_t u = (int32_t)c - m->d;
            if (u >= (int32_t)m->lo && u <= (int32_t)m->hi && u != (int32_t)c) return (uint32_t)u;
        } else if (c > m->lo && c <= m->hi + 1 && ((c - 1 - m->lo) & 1) == 0 && c - 1 <= m->hi) return c - 1;
    }
    return c;
}

