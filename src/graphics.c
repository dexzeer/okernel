// Multiboot info structure (partial — we need the framebuffer fields)
struct mboot_info {
    uint32_t flags;
    uint32_t mem_lower;
    uint32_t mem_upper;
    uint32_t boot_device;
    uint32_t cmdline;
    uint32_t mods_count;
    uint32_t mods_addr;
    uint32_t syms[4];
    uint32_t mmap_length;
    uint32_t mmap_addr;
    uint32_t drives_length;
    uint32_t drives_addr;
    uint32_t config_table;
    uint32_t boot_loader_name;
    uint32_t apm_table;
    // VBE fields (offset 28)
    uint32_t vbe_control_info;
    uint32_t vbe_mode_info;
    uint16_t vbe_mode;
    uint16_t vbe_interface_seg;
    uint16_t vbe_interface_off;
    uint16_t vbe_interface_len;
    // Framebuffer fields (offset 40)
    uint64_t framebuffer_addr;
    uint32_t framebuffer_pitch;
    uint32_t framebuffer_width;
    uint32_t framebuffer_height;
    uint8_t  framebuffer_bpp;
    uint8_t  framebuffer_type;
} __attribute__((packed));

void graphics_init(uint32_t mboot_addr) {
    struct mboot_info* mboot = (struct mboot_info*)mboot_addr;

    if (mboot->flags & (1 << 12)) {
        framebuffer = (uint8_t*)(uint32_t)mboot->framebuffer_addr;
        fb_pitch = mboot->framebuffer_pitch;
    } else {
        framebuffer = (uint8_t*)0xA0000;
        fb_pitch = SCREEN_W;
    }

    // Don't load wallpaper palette — keep default VGA colors for UI
    // Wallpaper will display with default palette colors

    for (int i = 0; i < SCREEN_W * SCREEN_H; i++) backbuffer[i] = 0;
    for (int i = 0; i < SCREEN_H; i++) dirty_rows[i] = 1;
}

void putpixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < SCREEN_W && y >= 0 && y < SCREEN_H) {
        backbuffer[y * SCREEN_W + x] = color;
        dirty_rows[y] = 1;
    }
}

void rect_fill(int x, int y, int w, int h, uint8_t color) {
    for (int j = y; j < y + h; j++) {
        if (j < 0 || j >= SCREEN_H) continue;
        dirty_rows[j] = 1;
        uint8_t* dst = backbuffer + j * SCREEN_W;
        int sx = x < 0 ? 0 : x;
        int ex = x + w > SCREEN_W ? SCREEN_W : x + w;
        for (int i = sx; i < ex; i++) dst[i] = color;
    }
}

void rect_outline(int x, int y, int w, int h, uint8_t color, int t) {
    for (int i = 0; i < t; i++) {
        hline(x + i, y + i, w - 2 * i, color);
        hline(x + i, y + h - 1 - i, w - 2 * i, color);
        vline(x + i, y + i, h - 2 * i, color);
        vline(x + w - 1 - i, y + i, h - 2 * i, color);
    }
}

void hline(int x, int y, int len, uint8_t color) {
    if (y < 0 || y >= SCREEN_H) return;
    if (x < 0) { len += x; x = 0; }
    if (x + len > SCREEN_W) len = SCREEN_W - x;
    if (len <= 0) return;
    uint8_t* dst = backbuffer + y * SCREEN_W + x;
    for (int i = 0; i < len; i++) dst[i] = color;
    dirty_rows[y] = 1;
}

void vline(int x, int y, int len, uint8_t color) {
    for (int i = 0; i < len; i++) {
        putpixel(x, y + i, color);
    }
}

void line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = x1 - x0;
    int dy = y1 - y0;
    int sx = dx > 0 ? 1 : -1;
    int sy = dy > 0 ? 1 : -1;
    dx = dx > 0 ? dx : -dx;
    dy = dy > 0 ? dy : -dy;
    int err = dx - dy;

    while (1) {
        putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx) { err += dx; y0 += sy; }
    }
}

void draw_char(int x, int y, char c, uint8_t fg, uint8_t bg) {
    int idx = c - 32;
    if (idx < 0 || idx > 95) return;

    for (int row = 0; row < 8; row++) {
        uint8_t bits = font8x8[idx][row];
        for (int col = 0; col < 8; col++) {
            uint8_t color = (bits & (1 << col)) ? fg : bg;
            if (color != bg) {
                putpixel(x + col, y + row, color);
            }
        }
    }
}

void draw_string(int x, int y, const char* str, uint8_t fg, uint8_t bg) {
    while (*str) {
        draw_char(x, y, *str, fg, bg);
        x += 8;
        str++;
    }
}

void draw_char_scaled(int x, int y, char c, uint8_t fg, uint8_t bg, int scale) {
    int idx = c - 32;
    if (idx < 0 || idx > 95) return;

    for (int row = 0; row < 8; row++) {
        uint8_t bits = font8x8[idx][row];
        for (int col = 0; col < 8; col++) {
            uint8_t color = (bits & (1 << col)) ? fg : bg;
            for (int sy = 0; sy < scale; sy++) {
                for (int sx = 0; sx < scale; sx++) {
                    putpixel(x + col * scale + sx, y + row * scale + sy, color);
                }
            }
        }
    }
}

void draw_string_scaled(int x, int y, const char* str, uint8_t fg, uint8_t bg, int scale) {
    while (*str) {
        draw_char_scaled(x, y, *str, fg, bg, scale);
        x += 8 * scale;
        str++;
    }
}

uint8_t* graphics_get_buffer(void) {
    return backbuffer;
}

void graphics_mark_dirty(int y) {
    if (y >= 0 && y < SCREEN_H) dirty_rows[y] = 1;
}

void graphics_write_pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < SCREEN_W && y >= 0 && y < SCREEN_H) {
        backbuffer[y * SCREEN_W + x] = color;
    }
}

// Cached wallpaper (pre-rendered at screen resolution)
static uint8_t cached_wallpaper[SCREEN_W * SCREEN_H];
static int wallpaper_cached = 0;

void graphics_cache_wallpaper(const unsigned char* pixels, int src_w, int src_h) {
    // Copy directly if same size, otherwise stretch
    if (src_w == SCREEN_W && src_h == SCREEN_H) {
        for (int i = 0; i < SCREEN_W * SCREEN_H; i++) {
            cached_wallpaper[i] = pixels[i];
        }
    } else {
        for (int y = 0; y < SCREEN_H; y++) {
            int src_y = (y * src_h) / SCREEN_H;
            for (int x = 0; x < SCREEN_W; x++) {
                int src_x = (x * src_w) / SCREEN_W;
                cached_wallpaper[y * SCREEN_W + x] = pixels[src_y * src_w + src_x];
            }
        }
    }
    wallpaper_cached = 1;
}

void graphics_blit_wallpaper(void) {
    if (!wallpaper_cached) return;
    for (int y = 0; y < SCREEN_H; y++) {
        uint8_t* dst = backbuffer + y * SCREEN_W;
        uint8_t* src = cached_wallpaper + y * SCREEN_W;
        int x = 0;
        for (; x <= SCREEN_W - 4; x += 4) {
            *(uint32_t*)(dst + x) = *(uint32_t*)(src + x);
        }
        for (; x < SCREEN_W; x++) dst[x] = src[x];
        dirty_rows[y] = 1;
    }
}

void graphics_fill(uint8_t color) {
    for (int y = 0; y < SCREEN_H; y++) {
        uint8_t* dst = backbuffer + y * SCREEN_W;
        for (int x = 0; x < SCREEN_W; x++) dst[x] = color;
        dirty_rows[y] = 1;
    }
}

void graphics_flush(void) {
    if (!framebuffer) return;
    for (int y = 0; y < SCREEN_H; y++) {
        if (!dirty_rows[y]) continue;
        uint8_t* src = backbuffer + y * SCREEN_W;
        uint8_t* dst = framebuffer + y * fb_pitch;
        int x = 0;
        for (; x <= SCREEN_W - 4; x += 4) {
            *(uint32_t*)(dst + x) = *(uint32_t*)(src + x);
        }
        for (; x < SCREEN_W; x++) dst[x] = src[x];
        dirty_rows[y] = 0;
    }
}

