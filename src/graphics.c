// Multiboot info structure
struct mboot_info {
    uint32_t flags;
    uint32_t mem_lower;
    uint32_t mem_upper;
    uint32_t boot_device;
    uint32_t cmdline;
    uint32_t mods_count;
    uint32_t mods_addr;
    uint32_t syms[4];
    uint32_t mmap_length;
    uint32_t mmap_addr;
    uint32_t drives_length;
    uint32_t drives_addr;
    uint32_t config_table;
    uint32_t boot_loader_name;
    uint32_t apm_table;
    uint32_t vbe_control_info;
    uint32_t vbe_mode_info;
    uint16_t vbe_mode;
    uint16_t vbe_interface_seg;
    uint16_t vbe_interface_off;
    uint16_t vbe_interface_len;
    uint64_t framebuffer_addr;
    uint32_t framebuffer_pitch;
    uint32_t framebuffer_width;
    uint32_t framebuffer_height;
    uint8_t  framebuffer_bpp;
    uint8_t  framebuffer_type;
} __attribute__((packed));

void graphics_init(uint32_t mboot_addr) {
    struct mboot_info* mboot = (struct mboot_info*)mboot_addr;

    if (mboot->flags & (1 << 12)) {
        framebuffer = (uint8_t*)(uint32_t)mboot->framebuffer_addr;
        fb_pitch = mboot->framebuffer_pitch;
    } else {
        framebuffer = (uint8_t*)0xA0000;
        fb_pitch = SCREEN_W * 4;
    }

    backbuffer = (uint32_t*)kmalloc(SCREEN_W * SCREEN_H * sizeof(uint32_t));
    dirty_rows = (uint8_t*)kmalloc(SCREEN_H * sizeof(uint8_t));
    if (!backbuffer || !dirty_rows) {
        serial_puts("[gfx] backbuffer alloc failed\n");
        return;
    }

    for (int i = 0; i < SCREEN_W * SCREEN_H; i++) backbuffer[i] = 0;
    for (int i = 0; i < SCREEN_H; i++) dirty_rows[i] = 1;
}

void graphics_set_clip(int x, int y, int w, int h) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    clip_x0 = x;
    clip_y0 = y;
    clip_x1 = x + w > SCREEN_W ? SCREEN_W : x + w;
    clip_y1 = y + h > SCREEN_H ? SCREEN_H : y + h;
    if (clip_x1 < clip_x0) clip_x1 = clip_x0;
    if (clip_y1 < clip_y0) clip_y1 = clip_y0;
}

void graphics_clip_reset(void) {
    clip_x0 = 0; clip_y0 = 0; clip_x1 = SCREEN_W; clip_y1 = SCREEN_H;
}

void putpixel(int x, int y, uint32_t color) {
    if (x >= clip_x0 && x < clip_x1 && y >= clip_y0 && y < clip_y1) {
        backbuffer[y * SCREEN_W + x] = color;
        dirty_rows[y] = 1;
    }
}

void rect_fill(int x, int y, int w, int h, uint32_t color) {
    int x0 = x < clip_x0 ? clip_x0 : x;
    int y0 = y < clip_y0 ? clip_y0 : y;
    int x1 = x + w < clip_x1 ? x + w : clip_x1;
    int y1 = y + h < clip_y1 ? y + h : clip_y1;
    if (x0 >= x1 || y0 >= y1) return;
    for (int j = y0; j < y1; j++) {
        dirty_rows[j] = 1;
        uint32_t* dst = backbuffer + j * SCREEN_W;
        for (int i = x0; i < x1; i++) dst[i] = color;
    }
}

void rect_outline(int x, int y, int w, int h, uint32_t color, int t) {
    for (int i = 0; i < t; i++) {
        hline(x + i, y + i, w - 2 * i, color);
        hline(x + i, y + h - 1 - i, w - 2 * i, color);
        vline(x + i, y + i, h - 2 * i, color);
        vline(x + w - 1 - i, y + i, h - 2 * i, color);
    }
}

// Linear gradient fill between c0 and c1. vertical=1 interpolates top->bottom,
// vertical=0 left->right. Used for browser chrome (tab strip, toolbar).
void gradient_fill(int x, int y, int w, int h, uint32_t c0, uint32_t c1, int vertical) {
    if (w <= 0 || h <= 0) return;
    uint8_t r0 = (c0 >> 16) & 0xFF, g0 = (c0 >> 8) & 0xFF, b0 = c0 & 0xFF;
    uint8_t r1 = (c1 >> 16) & 0xFF, g1 = (c1 >> 8) & 0xFF, b1 = c1 & 0xFF;
    int span = vertical ? h : w;
    for (int i = 0; i < span; i++) {
        int t = span > 1 ? (i * 255) / (span - 1) : 0;
        uint8_t r = r0 + (int)(r1 - r0) * t / 255;
        uint8_t g = g0 + (int)(g1 - g0) * t / 255;
        uint8_t b = b0 + (int)(b1 - b0) * t / 255;
        uint32_t col = ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
        if (vertical) hline(x, y + i, w, col);
        else          vline(x + i, y, h, col);
    }
}

void hline(int x, int y, int len, uint32_t color) {
    if (y < clip_y0 || y >= clip_y1) return;
    if (x < clip_x0) { len -= clip_x0 - x; x = clip_x0; }
    if (x + len > clip_x1) len = clip_x1 - x;
    if (len <= 0) return;
    uint32_t* dst = backbuffer + y * SCREEN_W + x;
    for (int i = 0; i < len; i++) dst[i] = color;
    dirty_rows[y] = 1;
}

void vline(int x, int y, int len, uint32_t color) {
    for (int i = 0; i < len; i++) putpixel(x, y + i, color);
}

void line(int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = x1 - x0, dy = y1 - y0;
    int sx = dx > 0 ? 1 : -1, sy = dy > 0 ? 1 : -1;
    dx = dx > 0 ? dx : -dx;
    dy = dy > 0 ? dy : -dy;
    int err = dx - dy;
    while (1) {
        putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx) { err += dx; y0 += sy; }
    }
}

// Per-glyph dimensions, set by glyph_rows() so the main font (possibly wide,
// >8px) and the extended 8x16 font can coexist. Single-threaded kernel, so
// globals are safe — glyph_rows() is always called before sampling a glyph.
static int g_gw = FONT_W, g_gh = FONT_H, g_gbpr = FONT_BPR;

// Glyph rows for a character: ASCII from font8x16, byte slots >= 0x80
// (Cyrillic + symbols, produced by the HTML decoder) from font8x16_ext.
static const uint8_t* glyph_rows(char c) {
    unsigned char u = (unsigned char)c;
    if (u < 32 || u == 127) return 0;
    if (u < 128) {
        g_gw = FONT_W; g_gh = FONT_H; g_gbpr = FONT_BPR;
        return font8x16[u - 32];
    }
    g_gw = FONT_EXT_W; g_gh = FONT_EXT_H; g_gbpr = FONT_EXT_BPR;
    return font8x16_ext[u - 0x80];
}

// Read one font bitmap pixel (1 if the glyph bit is set, 0 outside bounds).
// MSB-first within each row byte; rows are g_gbpr bytes wide.
static inline int font_bit(const uint8_t* glyph, int x, int y) {
    if (x < 0 || x >= g_gw || y < 0 || y >= g_gh) return 0;
    return (glyph[y * g_gbpr + (x >> 3)] >> (7 - (x & 7))) & 1;
}

// Blend fg over bg by coverage (0..cov_max), byte-order agnostic.
static uint32_t blend(uint32_t fg, uint32_t bg, int cov, int cov_max) {
    uint32_t out = 0;
    for (int i = 0; i < 4; i++) {
        int f = (fg >> (i * 8)) & 0xFF;
        int b = (bg >> (i * 8)) & 0xFF;
        int v = (f * cov + b * (cov_max - cov)) / cov_max;
        out |= ((uint32_t)(v & 0xFF)) << (i * 8);
    }
    return out;
}

// Glyph sampling: bilinear coverage of the bitmap at output pixel (ox,oy) of
// a tw x th target box. Edges come out as smooth gray instead of hard blocks —
// this is what makes an upscaled font readable instead of pixelated. Uses the
// per-glyph dimensions set by glyph_rows().
static uint32_t glyph_coverage(const uint8_t* glyph, int ox, int oy, int tw, int th) {
    int sxf = (ox * g_gw * 256 + g_gw * 128) / tw;   // 8.8 fixed, centered
    int syf = (oy * g_gh * 256 + g_gh * 128) / th;
    int x0 = sxf >> 8, fx = sxf & 255;
    int y0 = syf >> 8, fy = syf & 255;
    int x1 = (x0 + 1 < g_gw) ? x0 + 1 : x0;
    int y1 = (y0 + 1 < g_gh) ? y0 + 1 : y0;
    int v00 = font_bit(glyph, x0, y0), v10 = font_bit(glyph, x1, y0);
    int v01 = font_bit(glyph, x0, y1), v11 = font_bit(glyph, x1, y1);
    return v00 * (256 - fx) * (256 - fy) + v10 * fx * (256 - fy)
         + v01 * (256 - fx) * fy + v11 * fx * fy;       // 0..65536
}

void draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    draw_char_sized(x, y, c, fg, bg, CHAR_W, CHAR_H);
}

void draw_string(int x, int y, const char* str, uint32_t fg, uint32_t bg) {
    while (*str) { draw_char(x, y, *str, fg, bg); x += CHAR_W; str++; }
}

void draw_string_fg(int x, int y, const char* str, uint32_t fg) {
    while (*str) {
        const uint8_t* glyph = glyph_rows(*str);
        if (glyph) {
            for (int row = 0; row < g_gh; row++) {
                for (int col = 0; col < g_gw; col++)
                    if ((glyph[row * g_gbpr + (col >> 3)] >> (7 - (col & 7))) & 1)
                        for (int sy = 0; sy < FONT_SCALE; sy++)
                            for (int sx = 0; sx < FONT_SCALE; sx++)
                                putpixel(x + col * FONT_SCALE + sx,
                                         y + row * FONT_SCALE + sy, fg);
            }
        }
        x += CHAR_W; str++;
    }
}

// 1x text: glyphs at their NATIVE size (no FONT_SCALE doubling). For tight
// chrome — tab labels, URL bar — where the body font cannot fit and would be
// half-overpainted by the band below it.
void draw_char_1x(int x, int y, char c, uint32_t fg, uint32_t bg) {
    const uint8_t* glyph = glyph_rows(c);
    if (!glyph) return;
    for (int row = 0; row < g_gh; row++)
        for (int col = 0; col < g_gw; col++)
            putpixel(x + col, y + row,
                     ((glyph[row * g_gbpr + (col >> 3)] >> (7 - (col & 7))) & 1) ? fg : bg);
}

void draw_string_1x(int x, int y, const char* str, uint32_t fg, uint32_t bg) {
    while (*str) { draw_char_1x(x, y, *str, fg, bg); x += g_gw; str++; }
}

// Filled rect with rounded corners: the corner pixels are simply not drawn,
// so whatever is behind (gradients) shows through.
void round_rect_fill(int x, int y, int w, int h, uint32_t c, int r) {
    if (r > w / 2) r = w / 2;
    if (r > h / 2) r = h / 2;
    for (int row = 0; row < h; row++) {
        int inset = 0;
        if (row < r) inset = r - row;
        else if (row >= h - r) inset = r - (h - 1 - row);
        if (w - 2 * inset > 0) hline(x + inset, y + row, w - 2 * inset, c);
    }
}

void draw_char_scaled(int x, int y, char c, uint32_t fg, uint32_t bg, int scale) {
    const uint8_t* glyph = glyph_rows(c);
    if (!glyph) return;
    int s = scale * FONT_SCALE; // match draw_char: the base font renders at 2x
    for (int row = 0; row < g_gh; row++) {
        for (int col = 0; col < g_gw; col++) {
            uint32_t pixel = ((glyph[row * g_gbpr + (col >> 3)] >> (7 - (col & 7))) & 1) ? fg : bg;
            for (int sy = 0; sy < s; sy++)
                for (int sx = 0; sx < s; sx++)
                    putpixel(x + col * s + sx, y + row * s + sy, pixel);
        }
    }
}

void draw_string_scaled(int x, int y, const char* str, uint32_t fg, uint32_t bg, int scale) {
    while (*str) { draw_char_scaled(x, y, *str, fg, bg, scale); x += CHAR_W * scale; str++; }
}

// Render the 8x16 font into an exact tw x th screen box, anti-aliased via
// bilinear glyph sampling (smooth gray edges, not hard blocks). Content text
// uses this at CONTENT_GW x CONTENT_GH (12x24); OS/browser chrome via
// draw_char at CHAR_W x CHAR_H (16x32). Both upscale the small bitmap, so the
// smoothing is what makes the text readable instead of pixelated.
void draw_char_sized(int x, int y, char c, uint32_t fg, uint32_t bg, int tw, int th) {
    const uint8_t* glyph = glyph_rows(c);
    if (!glyph) return;
    for (int row = 0; row < th; row++) {
        for (int col = 0; col < tw; col++) {
            int cov = glyph_coverage(glyph, col, row, tw, th);
            putpixel(x + col, y + row, blend(fg, bg, cov, 65536));
        }
    }
}

uint32_t* graphics_get_buffer(void) { return backbuffer; }

void graphics_mark_dirty(int y) {
    if (y >= 0 && y < SCREEN_H) dirty_rows[y] = 1;
}

void graphics_write_pixel(int x, int y, uint32_t color) {
    if (x >= clip_x0 && x < clip_x1 && y >= clip_y0 && y < clip_y1)
        backbuffer[y * SCREEN_W + x] = color;
}

void graphics_blit_rect(int sx, int sy, int w, int h, int dx, int dy) {
    if (!backbuffer) return;
    // source rect clipped to screen
    int x0 = sx > 0 ? sx : 0;
    int y0 = sy > 0 ? sy : 0;
    int x1 = sx + w < SCREEN_W ? sx + w : SCREEN_W;
    int y1 = sy + h < SCREEN_H ? sy + h : SCREEN_H;
    if (x0 >= x1 || y0 >= y1) return;

    // copy in the direction that avoids overwriting unread source rows/
    // columns (overlap-safe memmove semantics)
    int ystep = dy > 0 ? -1 : 1;
    int ystart = dy > 0 ? y1 - 1 : y0;
    for (int y = ystart; y >= y0 && y < y1; y += ystep) {
        int ny = y + dy;
        if (ny < 0 || ny >= SCREEN_H) continue;
        uint32_t* src = backbuffer + y * SCREEN_W;
        uint32_t* dst = backbuffer + ny * SCREEN_W;
        if (dx > 0) {
            for (int x = x1 - 1; x >= x0; x--) {
                int nx = x + dx;
                if (nx < SCREEN_W) dst[nx] = src[x];
            }
        } else {
            for (int x = x0; x < x1; x++) {
                int nx = x + dx;
                if (nx >= 0) dst[nx] = src[x];
            }
        }
        dirty_rows[ny] = 1;
    }
}

// Wallpaper cache (dynamically allocated)
static uint32_t* cached_wallpaper = 0;
static int wallpaper_cached = 0;

void graphics_cache_wallpaper(const unsigned char* pixels, const unsigned char* palette, int src_w, int src_h) {
    if (!cached_wallpaper)
        cached_wallpaper = (uint32_t*)kmalloc(SCREEN_W * SCREEN_H * sizeof(uint32_t));
    if (!cached_wallpaper) {
        serial_puts("[gfx] wallpaper cache alloc failed\n");
        return;
    }

    // Map index -> palette RGB (0x00RRGGBB). The wallpaper has its own
    // 256-color palette — mapping through the 16-color VGA palette turns
    // every index >= 16 into flat grey.
    for (int y = 0; y < SCREEN_H; y++) {
        int src_y = (y * src_h) / SCREEN_H;
        for (int x = 0; x < SCREEN_W; x++) {
            int src_x = (x * src_w) / SCREEN_W;
            uint8_t idx = pixels[src_y * src_w + src_x];
            uint32_t r = palette[idx * 3];
            uint32_t g = palette[idx * 3 + 1];
            uint32_t b = palette[idx * 3 + 2];
            cached_wallpaper[y * SCREEN_W + x] = (r << 16) | (g << 8) | b;
        }
    }
    wallpaper_cached = 1;
}

void graphics_blit_wallpaper(void) {
    if (!wallpaper_cached || !cached_wallpaper) return;
    for (int y = 0; y < SCREEN_H; y++) {
        uint32_t* dst = backbuffer + y * SCREEN_W;
        uint32_t* src = cached_wallpaper + y * SCREEN_W;
        for (int x = 0; x < SCREEN_W; x++) dst[x] = src[x];
        dirty_rows[y] = 1;
    }
}

void graphics_blit_wallpaper_rect(int x, int y, int w, int h) {
    if (!wallpaper_cached || !cached_wallpaper) return;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > SCREEN_W) w = SCREEN_W - x;
    if (y + h > SCREEN_H) h = SCREEN_H - y;
    if (w <= 0 || h <= 0) return;
    for (int yy = y; yy < y + h; yy++) {
        uint32_t* dst = backbuffer + yy * SCREEN_W;
        uint32_t* src = cached_wallpaper + yy * SCREEN_W;
        for (int xx = x; xx < x + w; xx++) dst[xx] = src[xx];
        dirty_rows[yy] = 1;
    }
}

void graphics_fill(uint32_t color) {
    for (int y = 0; y < SCREEN_H; y++) {
        uint32_t* dst = backbuffer + y * SCREEN_W;
        for (int x = 0; x < SCREEN_W; x++) dst[x] = color;
        dirty_rows[y] = 1;
    }
}

void graphics_flush(void) {
    if (!framebuffer || !backbuffer) return;
    for (int y = 0; y < SCREEN_H; y++) {
        if (!dirty_rows[y]) continue;
        uint32_t* src = backbuffer + y * SCREEN_W;
        uint32_t* dst = (uint32_t*)(framebuffer + y * fb_pitch);
        for (int x = 0; x < SCREEN_W; x++) dst[x] = src[x];
        dirty_rows[y] = 0;
    }
}

void graphics_draw_bitmap(int x, int y, const uint8_t* bitmap, int bmp_w, int bmp_h, uint32_t fg, uint32_t bg, int scale) {
    for (int row = 0; row < bmp_h; row++)
        for (int col = 0; col < bmp_w; col++) {
            int byte_idx = col / 8, bit_idx = 7 - (col % 8);
            uint32_t pixel = (bitmap[row * ((bmp_w + 7) / 8) + byte_idx] & (1 << bit_idx)) ? fg : bg;
            for (int sy = 0; sy < scale; sy++)
                for (int sx = 0; sx < scale; sx++)
                    putpixel(x + col * scale + sx, y + row * scale + sy, pixel);
        }
}
