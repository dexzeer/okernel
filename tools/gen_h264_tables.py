# scans (Tables 8-13, 8-14): idx -> raster position i*N + j of c_ij (i = row), zig-zag and field
def parse_scan(title_re, n):
    s = find(title_re)
    e = s + 400
    toks = logical(s, e)
    res = {'zig-zag': [], 'field': []}
    i = 0
    while i < len(toks):
        if toks[i] in res and len(res[toks[i]]) < n * n:
            lab = toks[i]
            got = []
            j = i + 1
            while j < len(toks) and re.fullmatch(r'c\d\d', toks[j]) and len(got) < 16:
                got.append(toks[j]); j += 1
            res[lab] += got
            i = j
        else:
            i += 1
    for k, v in res.items():
        assert len(v) == n * n, (title_re, k, len(v))
        pos = [int(c[1]) * n + int(c[2]) for c in v]
        assert sorted(pos) == list(range(n * n)), (k, pos)
        res[k] = pos
    return res

