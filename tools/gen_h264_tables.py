"""Generate src/media/h264_tables.c from the text of ITU-T H.264 (02/2016).

    python3 tools/gen_h264_tables.py h264.txt > src/media/h264_tables.c

h264.txt is the PDF's text (PyMuPDF `page.get_text()`, pages in order, one cell per line).
Every table is parsed from the specification text and checked (prefix codes are complete or
prefix-free as the spec says, row/column counts match, every context index is present once)
before anything is written, so a mis-parsed table stops the run instead of corrupting a decode.
The extraction splits a few numbers across lines: a line that does not end in a space continues
on the next one.
"""
import re, sys

SRC = open(sys.argv[1], encoding='utf-8').read().split('\n')
MINUS = '−'


def logical(start, end, blank=None):
    """Cells of lines [start, end) with split numbers rejoined."""
    out = []
    cur = ''
    for i in range(start, end):
        l = SRC[i]
        if blank is not None and l.strip() == '' and l != '':
            if cur: out.append(cur.strip()); cur = ''
            out.append(blank); continue
        if l.startswith('=====PAGE'):
            if cur: out.append(cur.strip()); cur = ''
            continue
        cur += l
        if l.endswith(' ') or l == '':
            if cur.strip(): out.append(cur.strip())
            cur = ''
    if cur.strip(): out.append(cur.strip())
    return out


def find(pat, after=0, nth=0):
    n = 0
    for i in range(after, len(SRC)):
        if re.match(pat, SRC[i]) and '....' not in SRC[i]:
            if n == nth: return i
            n += 1
    raise SystemExit('not found: ' + pat)


def num(t):
    t = t.replace(MINUS, '-').replace(' ', '')
    return int(t)


def isnum(t):
    return re.fullmatch('[-' + MINUS + r']?\d+', t.replace(' ', '')) is not None


def isbits(t):
    return re.fullmatch('[01]+( [01]+)*', t) is not None


def check_prefix_free(codes, name, complete=False):
    cs = [c for c in codes if c is not None]
    for i, a in enumerate(cs):
        for j, b in enumerate(cs):
            if i != j and b.startswith(a):
                raise SystemExit(f'{name}: code {a} is a prefix of {b}')
    k = sum(2.0 ** -len(c) for c in cs)
    if complete and abs(k - 1.0) > 1e-9:
        raise SystemExit(f'{name}: Kraft sum {k} != 1')
    return k


