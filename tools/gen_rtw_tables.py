#!/usr/bin/env python3
"""Generate src/rtw/rtw_tables.c: the RTL8821C MAC / baseband / AGC / radio initialisation tables.

The tables are pure data (register address, value pairs with IF/ELSE condition markers) published in the Linux
rtw88 driver (rtw8821c_table.c); like the AAC code books (tools/gen_aac_tables.py) they were read out with the
user's permission - the code that applies them is our own (src/rtw/rtw_hw.c).

usage: gen_rtw_tables.py path/to/rtw8821c_table.c > src/rtw/rtw_tables.c
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()

def u32_array(name):
    m = re.search(r"static const u32 " + name + r"\[\] = \{(.*?)\n\};", src, re.S)
    if not m:
        sys.exit("missing table " + name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", body)]

def pg_array(name):
    m = re.search(r"static const struct rtw_phy_pg_cfg_pair " + name + r"\[\] = \{(.*?)\n\};", src, re.S)
    if not m:
        sys.exit("missing table " + name)
    rows = re.findall(r"\{([^}]*)\}", m.group(1))
    out = []
    for r in rows:
        out.append([int(x, 16) if x.strip().startswith("0x") else int(x) for x in r.replace(",", " ").split()])
    return out

def emit_u32(cname, vals):
    print("const uint32_t %s[] = {" % cname)
    for i in range(0, len(vals), 6):
        print("    " + ", ".join("0x%08x" % v for v in vals[i:i + 6]) + ",")
    print("};")
    print("const uint32_t %s_n = %d;\n" % (cname, len(vals)))

print("// Generated by tools/gen_rtw_tables.py from the rtw88 table data. Do not edit.")
print("#include <stdint.h>\n")
for cname, name in (("rtw_mac_tbl", "rtw8821c_mac"), ("rtw_agc_tbl", "rtw8821c_agc"), ("rtw_agc_btg2_tbl", "rtw8821c_agc_btg_type2"),
                    ("rtw_bb_tbl", "rtw8821c_bb"), ("rtw_rf_a_tbl", "rtw8821c_rf_a")):
    emit_u32(cname, u32_array(name))
pg = pg_array("rtw8821c_bb_pg_type0")
emit_u32("rtw_bb_pg_tbl", [v for row in pg for v in row])
