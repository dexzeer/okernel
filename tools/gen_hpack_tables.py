#!/usr/bin/env python3
"""Generate src/net/hpack_tables.c from the text of RFC 7541 (HPACK): the static table (Appendix A) and the Huffman code
(Appendix B). Nothing is typed in by hand; the numbers come straight out of the RFC.

    curl -s -o rfc7541.txt https://www.rfc-editor.org/rfc/rfc7541.txt
    python3 tools/gen_hpack_tables.py rfc7541.txt > src/net/hpack_tables.c
"""
import re
import sys

text = open(sys.argv[1], encoding='ascii', errors='replace').read()

# Appendix A: "| 12    | :status                     | 400           |"
a = text.index('Appendix A.  Static Table Definition')
b = text.index('Appendix B.  Huffman Code')
static = {}
for m in re.finditer(r'^\s*\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*([^|]*?)\s*\|\s*$', text[a:b], re.M):
    static[int(m.group(1))] = (m.group(2), m.group(3))
assert sorted(static) == list(range(1, 62)), sorted(static)

# Appendix B: "       ( 47)  |11111111|...                  18  [ 6]"  and "EOS (256)  |...   3fffffff  [30]"
c = text.index('Appendix C.  Examples')
codes = {}
for m in re.finditer(r'^\s*(?:EOS|\x27.{1,3}\x27)?\s*\(\s*(\d+)\)\s*\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]\s*$', text[b:c], re.M):
    codes[int(m.group(1))] = (int(m.group(2), 16), int(m.group(3)))
assert sorted(codes) == list(range(257)), [i for i in range(257) if i not in codes]
for s, (code, ln) in codes.items():
    assert 5 <= ln <= 30 and code < (1 << ln)

out = []
out.append('// GENERATED by tools/gen_hpack_tables.py from RFC 7541 (Appendix A static table, Appendix B Huffman code). Do not edit.')
out.append('#include "hpack.h"')
out.append('')
out.append('const struct hpack_static hpack_static_table[61] = {')
for i in range(1, 62):
    n, v = static[i]
    out.append('    { "%s", "%s" },   /* %d */' % (n, v, i))
out.append('};')
out.append('')
out.append('// Huffman code of each symbol 0..255 and EOS (256): code in the low `len` bits.')
out.append('const uint32_t hpack_huff_code[257] = {')
row = []
for s in range(257):
    row.append('0x%x' % codes[s][0])
    if len(row) == 8:
        out.append('    ' + ', '.join(row) + ',')
        row = []
if row: out.append('    ' + ', '.join(row) + ',')
out.append('};')
out.append('const uint8_t hpack_huff_len[257] = {')
row = []
for s in range(257):
    row.append(str(codes[s][1]))
    if len(row) == 16:
        out.append('    ' + ', '.join(row) + ',')
        row = []
if row: out.append('    ' + ', '.join(row) + ',')
out.append('};')
print('\n'.join(out))
