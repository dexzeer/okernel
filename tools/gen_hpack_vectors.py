#!/usr/bin/env python3
"""Extract the worked examples of RFC 7541 Appendix C (header blocks and the header lists they decode to) into a C include
for tests/test_hpack.c.

    python3 tools/gen_hpack_vectors.py rfc7541.txt > tests/hpack_vectors.inc
"""
import re
import sys

text = open(sys.argv[1], encoding='ascii', errors='replace').read()
text = text[text.index('Appendix C.  Examples'):]
secs = re.split(r'\n(?=C\.\d\.\d\.\s)', text)
print('// GENERATED by tools/gen_hpack_vectors.py from RFC 7541 Appendix C. Do not edit.')
print('struct hv { int group; const char* hex; const char* expect; };')
print('static const struct hv HV[] = {')
n = 0
for sec in secs:
    m = re.match(r'C\.(\d)\.(\d)\.', sec)
    if not m:
        continue
    grp = int(m.group(1))
    hx = re.search(r'Hex dump of encoded data:\n+((?:[ ]+[0-9a-f ]+\|[^\n]*\n)+)', sec)
    if not hx:
        continue
    hexs = ''.join(re.findall(r'^[ ]+([0-9a-f ]+?)\s*\|', hx.group(1), re.M)).replace(' ', '')
    dl = re.search(r'Decoded header list:\n+((?:[ ]+[:a-z0-9-]+: [^\n]*\n)+)', sec)
    lines = [l.strip() for l in dl.group(1).split('\n') if l.strip()]
    exp = ''.join(l.replace('\\', '\\\\').replace('"', '\\"') + '\\n' for l in lines)
    print('    { %d, "%s", "%s" },' % (grp, hexs, exp))
    n += 1
print('};')
print('#define NHV %d' % n)
