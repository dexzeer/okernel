#!/usr/bin/env python3
"""Generate src/media/celt_tables.c: the constant data tables of the Opus CELT layer
(RFC 6716 section 4.3): band layout, static bit allocation, energy probability
models, pulse caches. These are numbers defined by the standard (like the Unicode
data in gen_unicode.py); they are read from the RFC's reference source and written
out as plain arrays. No code is taken from it.

    python3 tools/gen_celt_tables.py <path to the extracted RFC 6716 source>/celt > src/media/celt_tables.c
"""
import re, sys

def arr(text, name, cast=int):
    """Numbers of `name[...] = { ... };` in text (comments stripped)."""
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^\]]*\])+\s*=\s*\{', text)
    if not m:
        raise SystemExit("table not found: " + name)
    i = m.end() - 1
    depth, j = 0, i
    while True:
        c = text[j]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    body = re.sub(r'/\*.*?\*/', '', text[i:j + 1], flags=re.S)
    return [cast(x) for x in re.findall(r'-?\d+\.?\d*(?:e[-+]?\d+)?', body)]

def emit(name, ctype, values, per=12, fmt=str):
    lines = ["const %s %s[%d] = {" % (ctype, name, len(values))]
    for k in range(0, len(values), per):
        lines.append("    " + ", ".join(fmt(v) for v in values[k:k + per]) + ",")
    lines.append("};")
    return "\n".join(lines)

def main():
    d = sys.argv[1]
    modes = open(d + "/modes.c").read()
    static = open(d + "/static_modes_float.h").read()
    qb = open(d + "/quant_bands.c").read()
    out = ["// GENERATED by tools/gen_celt_tables.py - constant tables of the Opus CELT layer",
           "// (RFC 6716 4.3). Do not edit.", '#include "celt_tables.h"', ""]
    out.append(emit("celt_eband5ms", "int16_t", arr(modes, "eband5ms"), 22))
    out.append(emit("celt_band_alloc", "uint8_t", arr(modes, "band_allocation"), 21))
    out.append(emit("celt_logN", "int16_t", arr(static, "logN400"), 21))
    out.append(emit("celt_cache_index", "int16_t", arr(static, "cache_index50"), 15))
    out.append(emit("celt_cache_bits", "uint8_t", arr(static, "cache_bits50"), 16))
    out.append(emit("celt_cache_caps", "uint8_t", arr(static, "cache_caps50"), 21))
    out.append(emit("celt_window120", "float", arr(static, "window120", float), 5, lambda v: repr(v) + "f"))
    # energy model: [LM][intra][42]
    e = arr(qb, "e_prob_model")
    assert len(e) == 4 * 2 * 42, len(e)
    out.append(emit("celt_e_prob_model", "uint8_t", e, 14))
    # mean band energies (the fixed-point table is in Q4 (x16); the float table is the same /16)
    means = re.search(r'eMeans\[25\]\s*=\s*\{([^}]*)\}', qb[qb.index("#ifdef FIXED_POINT"):], re.S)
    m6 = [int(x) for x in re.findall(r'-?\d+', means.group(1))]
    assert len(m6) == 25
    out.append("const float celt_eMeans[25] = {")
    out.append("    " + ", ".join(repr(v / 16.0) + "f" for v in m6) + ",")
    out.append("};")
    print("\n".join(out))

main()
