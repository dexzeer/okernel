#!/usr/bin/env python3
"""Generate src/web/charsets_mb.h — multibyte CJK decoding tables for the okai
charset decoder (GBK/gb18030, Shift_JIS, Big5), from the WHATWG Encoding
Standard index files (https://encoding.spec.whatwg.org/):

    python3 tools/gen_mbcharsets.py <dir-with-index-*.txt> > src/web/charsets_mb.h

index-gb18030.txt is dense (pointer 0..23939); index-jis0208.txt (0..11103) and
index-big5.txt (0..19781) are sparse — holes decode as U+FFFD.
"""
import sys, os

D = sys.argv[1]

def rd(name):
    with open(os.path.join(D, name), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                yield line.split("\t")

def load(name, size):
    idx = [0xFFFF] * size
    n = 0
    for f in rd(name):
        p, cp = int(f[0]), int(f[1], 16)
        idx[p] = cp
        n += 1
    return idx, n

gb, _ = load("index-gb18030.txt", 23940)
jis, jn = load("index-jis0208.txt", 11104)
big5, bn = load("index-big5.txt", 19782)

# gb18030 four-byte ranges: the spec's "index gb18030 ranges" (pointer -> code point)
ranges = []
for f in rd("index-gb18030-ranges.txt"):
    ranges.append((int(f[0]), int(f[1], 16)))

out = []
w = out.append
def blank():
    out.append("")
w("// GENERATED by tools/gen_mbcharsets.py - WHATWG multibyte CJK index tables.")
w("#ifndef WEB_CHARSETS_MB_H")
w("#define WEB_CHARSETS_MB_H")
w("#include <stdint.h>")
blank()
def emit(name, vals, per=14):
    w("static const uint16_t %s[] = {" % name)
    for i in range(0, len(vals), per):
        w("  " + ",".join(str(v) for v in vals[i:i + per]) + ",")
    w("};")
    blank()
emit("wmb_gb18030", gb)
emit("wmb_jis0208", jis)
emit("wmb_big5", big5)
w("// gb18030 four-byte ranges: (start pointer, code point at it), sorted")
w("static const uint32_t wmb_gb_ranges[%d][2] = {" % len(ranges))
for i in range(0, len(ranges), 4):
    w("  " + ",".join("{%d,%d}" % r for r in ranges[i:i + 4]) + ",")
w("};")
w("// holes decode as 0xFFFD; sizes: gb18030 %d, jis0208 %d (%d mapped), big5 %d (%d mapped)" % (len(gb), len(jis), jn, len(big5), bn))
blank()
w("enum { WMB_GBK = 0, WMB_GB18030, WMB_SJIS, WMB_BIG5, WMB_COUNT };")
w("struct wmbcs { const char* const* labels; uint8_t type; };")
w("static const char* const wmb_lab_gbk[] = {\"gbk\",\"chinese\",\"csgb2312\",\"csiso58gb231280\",\"gb_2312\",\"gb_2312-80\",\"iso-ir-58\",\"x-gbk\",0};")
w("static const char* const wmb_lab_gb18030[] = {\"gb18030\",0};")
w("static const char* const wmb_lab_sjis[] = {\"shift_jis\",\"csshiftjis\",\"ms932\",\"ms_kanji\",\"shift-jis\",\"sjis\",\"windows-31j\",\"x-sjis\",0};")
w("static const char* const wmb_lab_big5[] = {\"big5\",\"big5-hkscs\",\"cn-big5\",\"csbig5\",\"x-x-big5\",0};")
w("static const struct wmbcs wmbcs_table[WMB_COUNT] = {")
w("  { wmb_lab_gbk, WMB_GBK }, { wmb_lab_gb18030, WMB_GB18030 },")
w("  { wmb_lab_sjis, WMB_SJIS }, { wmb_lab_big5, WMB_BIG5 },")
w("};")
blank()
w("#endif")
print("\n".join(out))
